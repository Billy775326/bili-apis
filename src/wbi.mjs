import {createHash} from 'node:crypto';
// Derived from the served PC frontend; source hashes and offsets are in evidence/pc-wbi-source.json.
export const WBI_PERMUTATION=Object.freeze([46,47,18,2,53,8,23,32,15,50,10,31,58,3,45,35,27,43,5,49,33,9,42,19,29,28,14,39,12,38,41,13,37,48,7,16,24,55,40,61,26,17,0,1,60,51,30,4,22,25,54,21,56,59,6,63,57,62,11,36,20,34,44,52]);
export function wbiKeysFromNav(json){
 const image=json?.data?.wbi_img;
 function key(url){if(typeof url!=='string')throw Error('Missing WBI image URL');const value=new URL(url).pathname.split('/').at(-1).split('.')[0];if(!/^[a-fA-F0-9]{32}$/.test(value))throw Error('Invalid WBI image key');return value;}
 return {imgKey:key(image?.img_url),subKey:key(image?.sub_url)};
}
export function signWbi(params,{imgKey,subKey,nowSeconds=Math.round(Date.now()/1000)}){
 if(!params||typeof params!=='object'||Array.isArray(params))throw Error('WBI parameters must be an object');
 if(!/^[a-fA-F0-9]{32}$/.test(imgKey)||!/^[a-fA-F0-9]{32}$/.test(subKey))throw Error('WBI keys must each contain 32 hex characters');
 if(!Number.isSafeInteger(nowSeconds)||nowSeconds<0)throw Error('WBI time must be nonnegative integer UTC epoch seconds');
 if(Object.hasOwn(params,'w_rid')||Object.hasOwn(params,'wts'))throw Error('w_rid and wts are generated by the signer');
 const mixin=WBI_PERMUTATION.map(i=>(imgKey+subKey)[i]).join('').slice(0,32),values=Object.create(null),canonicalValues=Object.create(null);
 for(const [key,value]of Object.entries({...params,wts:nowSeconds})){
  if(value===null||value===undefined)continue;
  if(!['string','number','boolean'].includes(typeof value)||(typeof value==='number'&&!Number.isFinite(value)))throw Error('WBI parameters must be finite scalars: '+key);
  values[key]=value;canonicalValues[key]=typeof value==='string'?value.replace(/[!'()*]/g,''):value;
 }
 const encode=object=>Object.keys(object).sort().map(k=>encodeURIComponent(k)+'='+encodeURIComponent(object[k])).join('&');
 const canonicalQuery=encode(canonicalValues),w_rid=createHash('md5').update(canonicalQuery+mixin).digest('hex');
 // The served frontend sanitizes only the digest input and sends the original scalar values.
 return {query:encode(values)+'&w_rid='+w_rid,canonicalQuery,parameters:{...values,w_rid}};
}
